/// <summary>
/// 通常フェーズ(TomsShop)内のターン進行マクロフェーズ。
/// イベント → 仕入れ → 商品陳列 → 営業 の順に進む。
/// </summary>
public enum TurnPhase
{
    Event,        // ランダムイベントの発生・処理
    Procurement,  // 仕入れ（情報屋/鍛冶屋/道具屋/ダンジョンLv/広告/ヒーロー/マップ）
    Display,       // 商品陳列（陳列設定＋預言者/需要ダッシュボード）
    Sales,         // 営業（自動進行→売上結果→次ターン）
}
